/**
 * HotelBookingApp
 *
 * This class represents the entry point of the Hotel Booking Application.
 * It demonstrates how a Java program begins execution and produces console output.
 * When the program runs, the JVM invokes the main() method, which prints a
 * welcome message along with the application name and version information.
 *
 * This example illustrates basic Java concepts such as:
 * - Class structure
 * - main() method as program entry point
 * - Console output using System.out.println()
 * - Linear program execution
 *
 * @author Softy
 * @version 1.0
 */

public class BookMyStayApp {

    /**
     * The main method is the entry point of the Java application.
     * The JVM starts execution from this method.
     *
     * @param args command line arguments
     */
    public static void main(String[] args) {

        // Display welcome message
        System.out.println("Welcome to the Hotel Booking System");

        // Display application name and version
        System.out.println("Application: Hotel Booking System v1.0");

        // Inform user that system has started successfully
        System.out.println("System initialized successfully.");

    }
}